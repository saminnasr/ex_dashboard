-- 1) ساخت جدول اطلاعات مراجعین
create table if not exists public.exhibition_visitors (
  id bigint generated by default as identity primary key,
  visitor_name text,
  company text,
  activity_service text,
  phone text,
  extra_notes text,
  created_at timestamptz not null default now()
);

-- 2) فعال‌سازی RLS
alter table public.exhibition_visitors enable row level security;

-- 3) دسترسی فقط برای خواندن عمومی
-- هر شخصی که لینک داشبورد و آدرس/کلید عمومی سایت را داشته باشد،
-- می‌تواند همه ردیف‌ها را بخواند. هیچ دسترسی نوشتن داده نمی‌شود.
drop policy if exists "Public can read exhibition visitors" on public.exhibition_visitors;
create policy "Public can read exhibition visitors"
on public.exhibition_visitors
for select
to anon, authenticated
using (true);

grant usage on schema public to anon, authenticated;
grant select on table public.exhibition_visitors to anon, authenticated;

-- عمداً هیچ policy یا grant برای INSERT / UPDATE / DELETE تعریف نشده است.
